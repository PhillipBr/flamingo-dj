create table if not exists public.dj_match_feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  source_track_id text not null,
  target_track_id text not null,
  source_playlist_id text,
  target_playlist_id text,
  rating smallint not null check (rating between 0 and 3),
  technical_score numeric not null default 0,
  bpm_score numeric not null default 0,
  key_score numeric not null default 0,
  energy_score numeric not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists dj_match_feedback_unique_transition
on public.dj_match_feedback (
  user_id,
  source_track_id,
  target_track_id,
  coalesce(source_playlist_id, ''),
  coalesce(target_playlist_id, '')
);

alter table public.dj_match_feedback enable row level security;

drop policy if exists "match_feedback_select_own" on public.dj_match_feedback;
create policy "match_feedback_select_own"
on public.dj_match_feedback for select to authenticated
using (auth.uid() = user_id);

drop policy if exists "match_feedback_insert_own" on public.dj_match_feedback;
create policy "match_feedback_insert_own"
on public.dj_match_feedback for insert to authenticated
with check (auth.uid() = user_id);

drop policy if exists "match_feedback_update_own" on public.dj_match_feedback;
create policy "match_feedback_update_own"
on public.dj_match_feedback for update to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);
